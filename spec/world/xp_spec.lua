local xp = require("hwc.world.xp")
local config = require("hwc.config")
local sandbox = require("hwc.sandbox")
local stubs = require("hwc.stubs.core")
local World = require("hwc.world")

local function setup(level)
  local cfg = config.load({ race = "Dwarf", class = "WARRIOR" })
  local sb = sandbox.new(cfg)
  sb.world = World.new(cfg, nil, sb.clock)
  stubs.install(sb, cfg)
  if level then sb.world.player.level = level end
  return sb, sb.env, sb.world.player
end

describe("xp rules", function()
  it("gives the Classic XP to next level for levels 1-25", function()
    assert.equal(400, xp.to_next(1))
    assert.equal(29400, xp.to_next(23))
    assert.equal(31700, xp.to_next(24))
    assert.equal(34000, xp.to_next(25))
  end)

  it("errors outside levels 1-25", function()
    assert.has_error(function() xp.to_next(0) end)
    assert.has_error(function() xp.to_next(26) end)
  end)

  it("scales quest XP by the level difference and floors the result", function()
    assert.equal(80, xp.quest_xp(80, 1, 1))
    assert.equal(400, xp.quest_xp(1000, 20, 12))
    assert.equal(1000, xp.quest_xp(1000, 20, 15))
    assert.equal(600, xp.quest_xp(1000, 20, 13))
    assert.equal(100, xp.quest_xp(1000, 20, 9))
    assert.equal(100, xp.quest_xp(1000, 20, 1))
  end)

  it("gives gray level and zero difference from the Classic bands", function()
    assert.equal(0, xp.gray_level(5))
    assert.equal(4, xp.gray_level(10))
    assert.equal(5, xp.zero_diff(7))
    assert.equal(7, xp.zero_diff(11))
    assert.equal(11, xp.zero_diff(25))
  end)

  it("gives mob XP by level difference, grey, and elite and party bonus", function()
    assert.equal(95, xp.mob_xp(10, 10, false, 1))
    assert.equal(104.5, xp.mob_xp(10, 12, false, 1))
    assert.equal(0, xp.mob_xp(10, 4, false, 1))
    assert.equal(190, xp.mob_xp(10, 10, true, 1))
    assert.equal(95, xp.mob_xp(10, 10, false, 2) * 2)
  end)
end)

describe("Player levelling", function()
  it("carries the remainder across levels", function()
    local _, env, p = setup()
    assert.equal(2, p:add_xp(2000))
    assert.equal(3, env.UnitLevel("player"))
    assert.equal(700, env.UnitXP("player"))
    assert.equal(1400, env.UnitXPMax("player"))
  end)

  it("discards XP at the level 26 cap and never errors in UnitXPMax", function()
    local _, env, p = setup(25)
    assert.equal(1, p:add_xp(100000))
    assert.equal(26, env.UnitLevel("player"))
    assert.equal(0, env.UnitXP("player"))
    assert.equal(0, p:add_xp(5000))
    assert.equal(0, env.UnitXP("player"))
    assert.equal(0, env.UnitXPMax("player"))
  end)
end)
