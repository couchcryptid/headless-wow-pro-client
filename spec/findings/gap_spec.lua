local gap = require("hwc.findings.gap")

describe("findings.gap", function()
  it("grades low under 2, medium from 2, high from 4", function()
    assert.equal("low", gap.severity(0))
    assert.equal("low", gap.severity(1.9))
    assert.equal("medium", gap.severity(2))
    assert.equal("medium", gap.severity(3.9))
    assert.equal("high", gap.severity(4))
    assert.equal("high", gap.severity(5.5))
  end)
  it("words a gap to one decimal, or less than 0.1 below 0.05", function()
    assert.equal("0.9", gap.text(0.9))
    assert.equal("2.0", gap.text(2))
    assert.equal("less than 0.1", gap.text(0.04))
    assert.equal("less than 0.1", gap.text(0))
  end)
  it("rounds to one decimal", function()
    assert.equal(1.4, gap.round(1.4399))
    assert.equal(0.1, gap.round(0.05))
  end)
  it("carries the margin sentence", function()
    assert.equal("Gaps under 2 levels are within what the simulation's missing XP explains "
      .. "(no incidental kills or rested XP).", gap.MARGIN_SENTENCE)
  end)
end)
