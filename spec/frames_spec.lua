local clock = require("hwc.clock")
local frames = require("hwc.frames")

describe("frames", function()
  local c, F
  before_each(function()
    c = clock.new()
    F = frames.new(c)
  end)

  it("delivers events only to registered frames, with args, in registration order", function()
    local log = {}
    local a, b, other = F:create("Frame"), F:create("Frame"), F:create("Frame")
    b:SetScript("OnEvent", function(self, ev, x, y) log[#log + 1] = { "b", self == b, ev, x, y } end)
    a:SetScript("OnEvent", function(self, ev, x, y) log[#log + 1] = { "a", self == a, ev, x, y } end)
    other:SetScript("OnEvent", function() log[#log + 1] = { "other" } end)
    b:RegisterEvent("PING")
    a:RegisterEvent("PING")
    other:RegisterEvent("PONG")
    assert.is_true(a:IsEventRegistered("PING"))
    assert.is_false(a:IsEventRegistered("PONG"))
    F:fire("PING", 1, 2)
    assert.are.same({ { "b", true, "PING", 1, 2 }, { "a", true, "PING", 1, 2 } }, log)
    a:UnregisterEvent("PING")
    log = {}
    F:fire("PING", 3)
    assert.are.equal(1, #log)
  end)

  it("delivers to hidden frames, RegisterAllEvents frames, and skips frames without OnEvent", function()
    local got = {}
    local h = F:create("Frame")
    h:Hide()
    h:SetScript("OnEvent", function(_, ev) got[#got + 1] = "h" .. ev end)
    h:RegisterEvent("X")
    local all = F:create("Frame")
    all:SetScript("OnEvent", function(_, ev) got[#got + 1] = "all" .. ev end)
    all:RegisterAllEvents()
    local bare = F:create("Frame")
    bare:RegisterEvent("X")
    F:fire("X")
    assert.are.same({ "hX", "allX" }, got)
  end)

  it("IsVisible is false when a parent is hidden", function()
    local p = F:create("Frame")
    local ch = F:create("Frame", nil, p)
    assert.is_true(ch:IsVisible())
    p:Hide()
    assert.is_true(ch:IsShown())
    assert.is_false(ch:IsVisible())
    assert.is_false(F:shown(ch))
    p:Show()
    assert.is_true(F:shown(ch))
  end)

  it("runs OnUpdate during settle only while shown, one ticker per frame", function()
    local f = F:create("Frame")
    local n, m = 0, 0
    f:SetScript("OnUpdate", function(self, el) assert.are.equal(f, self); n = n + 1 end)
    f:SetScript("OnUpdate", function() m = m + 1 end)
    c:after(0.2, function() end)
    c:settle()
    assert.are.equal(0, n)
    local ran = m
    assert.is_true(ran > 0)
    f:Hide()
    c:after(0.2, function() end)
    c:settle()
    assert.are.equal(ran, m)
    f:Show()
    f:SetScript("OnUpdate", nil)
    c:after(0.2, function() end)
    c:settle()
    assert.are.equal(ran, m)
  end)

  it("HookScript chains after the existing script", function()
    local f, order = F:create("Frame"), {}
    f:SetScript("OnShow", function() order[#order + 1] = 1 end)
    f:HookScript("OnShow", function() order[#order + 1] = 2 end)
    f:GetScript("OnShow")(f)
    assert.are.same({ 1, 2 }, order)
  end)

  it("unknown methods are chainable and Create* return child frames", function()
    local f = F:create("Frame", "MyFrame")
    assert.has_no.errors(function() f:SetPoint("TOP"):SetSize(1, 1) end)
    local fs = f:CreateFontString()
    assert.are.equal(f, fs:GetParent())
    fs:SetText("x")
    assert.are.equal("x", fs:GetText())
    f:SetChecked(true)
    assert.is_true(f:GetChecked())
    assert.are.equal(f, F:get("MyFrame"))
    assert.are.equal("MyFrame", f:GetName())
  end)

  it("SetParent/GetParent work", function()
    local p, f = F:create("Frame"), F:create("Frame")
    f:SetParent(p)
    assert.are.equal(p, f:GetParent())
  end)

  it("returns nil for unset data fields and non-string keys, but PascalCase methods still chain", function()
    local f = F:create("Frame")
    assert.is_nil(f.index)
    assert.is_nil(f.someField)
    assert.is_nil(f[1])
    assert.are.equal(f, f:SetPoint("TOP"))
    f.index = 3
    assert.are.equal(3, f.index)
  end)
  -- The client reports script errors to the error handler and keeps running
  -- other frames' scripts (WoWPro_Broker.lua:4853 errors inside OnUpdate headless).
  it("reports OnEvent and OnUpdate errors through on_error and keeps going", function()
    local seen = {}
    local G = frames.new(c, function(e) seen[#seen + 1] = tostring(e) end)
    local bad, good = G:create("Frame"), G:create("Frame")
    local got = 0
    bad:SetScript("OnEvent", function() error("ev-boom") end)
    good:SetScript("OnEvent", function() got = got + 1 end)
    bad:RegisterEvent("PING"); good:RegisterEvent("PING")
    G:fire("PING")
    assert.equal(1, got)
    local ticks = 0
    bad:SetScript("OnUpdate", function() error("up-boom") end)
    good:SetScript("OnUpdate", function() ticks = ticks + 1 end)
    c:after(0.1, function() end)
    c:settle()
    assert.is_true(ticks > 0)
    assert.matches("ev%-boom", seen[1])
    assert.matches("up%-boom", seen[2])
  end)
  -- WoWPro_Frames.lua:1132-1133 does arithmetic on GetWidth()
  it("keeps size state; unsized frames are 0 x 0", function()
    local f = F:create("Frame")
    assert.same({ 0, 0 }, { f:GetWidth(), f:GetHeight() })
    f:SetSize(30, 20)
    assert.same({ 30, 20 }, { f:GetSize() })
    f:SetWidth(5); f:SetHeight(6)
    assert.same({ 5, 6 }, { f:GetWidth(), f:GetHeight() })
  end)
  -- Getters used by the loaded files (WoWPro_Frames.lua, WoWPro_RowUpdate.lua) keep state;
  -- an unknown getter returns nil (never a truthy frame) and is reported once.
  it("keeps level, scale, points, enabled, attribute, value and text state", function()
    local p = F:create("Frame")
    local f = F:create("Button", nil, p)
    assert.equal(0, p:GetFrameLevel()); assert.equal(1, f:GetFrameLevel())
    f:SetFrameLevel(7); assert.equal(7, f:GetFrameLevel())
    p:SetScale(2); f:SetScale(0.5)
    assert.equal(0.5, f:GetScale()); assert.equal(1, f:GetEffectiveScale())
    assert.is_nil(f:GetPoint()); assert.equal(0, f:GetNumPoints())
    f:SetPoint("TOPLEFT", p, "BOTTOMLEFT", 3, 4)
    assert.same({ "TOPLEFT", p, "BOTTOMLEFT", 3, 4 }, { f:GetPoint(1) })
    f:ClearAllPoints(); assert.equal(0, f:GetNumPoints())
    assert.is_nil(f:GetTop()); assert.is_nil(f:GetLeft())
    assert.is_true(f:IsEnabled()); f:Disable(); assert.is_false(f:IsEnabled()); f:Enable()
    assert.is_true(f:IsEnabled())
    f:SetAttribute("type", "item"); assert.equal("item", f:GetAttribute("type"))
    f:SetValue(3); assert.equal(3, f:GetValue())
    f:SetTexture("t"); assert.equal("t", f:GetTexture())
    f:SetFont("F", 12, ""); assert.same({ "F", 12, "" }, { f:GetFont() })
    f:SetTextColor(1, 0.5, 0); assert.same({ 1, 0.5, 0, 1 }, { f:GetTextColor() })
    assert.equal(0, f:GetStringHeight()); assert.equal(0, f:GetStringWidth())
    assert.is_false(f:IsMouseOver())
  end)

  it("unknown getters return nil and are reported once", function()
    local misses = {}
    local G = frames.new(c, nil, function(name) misses[#misses + 1] = name end)
    local f = G:create("Frame")
    assert.is_nil(f:GetWhatever()); assert.is_nil(f:IsWhatever()); f:GetWhatever()
    assert.same({ "Frame:GetWhatever", "Frame:IsWhatever" }, misses)
    assert.equal(f, f:SetWhatever(1))
  end)
  -- WoWPro_Widgets.lua:457-461 and :497-498 (slot textures, slider range)
  it("slot textures are regions created by their setter; slider range is kept", function()
    local b = F:create("Button")
    assert.is_nil(b:GetNormalTexture())
    b:SetNormalTexture("path")
    local t = b:GetNormalTexture()
    assert.equal("path", t:GetTexture())
    assert.equal(b, t:GetParent())
    b:SetNormalTexture("other")
    assert.equal(t, b:GetNormalTexture())
    assert.equal("other", t:GetTexture())
    local s = F:create("Slider")
    s:SetMinMaxValues(0, 10)
    assert.same({ 0, 10 }, { s:GetMinMaxValues() })
  end)
end)
